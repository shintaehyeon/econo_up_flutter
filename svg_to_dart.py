def parse_svg(s, path_name):
    tokens = re.findall(r'[A-Za-z]|[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?', s)
    i = 0
    cmd = ''
    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
        
        if cmd == 'M':
            x, y = tokens[i], tokens[i+1]
            print(f"{path_name}.moveTo({x}, {y});")
            i += 2
        elif cmd == 'L':
            x, y = tokens[i], tokens[i+1]
            print(f"{path_name}.lineTo({x}, {y});")
            i += 2
        elif cmd == 'C':
            x1, y1, x2, y2, x, y = tokens[i:i+6]
            print(f"{path_name}.cubicTo({x1}, {y1}, {x2}, {y2}, {x}, {y});")
            i += 6
        elif cmd == 'Z':
            print(f"{path_name}.close();")

